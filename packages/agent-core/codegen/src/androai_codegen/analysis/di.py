"""Dependency injection and architecture components: Hilt, Dagger, Koin, ViewModels.

Hilt and Dagger are read from their annotations (``@HiltAndroidApp``, ``@AndroidEntryPoint``,
``@HiltViewModel``, ``@Module`` + ``@InstallIn``, ``@Provides``, ``@Binds``, ``@Inject``,
``@Component``). Koin is read from its DSL (``startKoin``, ``module { single { ... } }``,
``by inject()``). ViewModel use is read from ``viewModels()``, ``hiltViewModel()``,
``koinViewModel()`` and ``ViewModelProvider``, in properties, parameter defaults and function
bodies.

Generated code (``Hilt_*``, ``Dagger*``, ``*_Impl``) is not in the sources and is not analysed;
the report says so. Nothing is concluded from its absence.
"""

from __future__ import annotations

import re

from .annotations import Annotation
from .catalog import accepted
from .context import Run
from .members import FileInfo, Member, TypeInfo
from .resolve import import_index
from .screens import lambda_span, project_calls
from .store import make_id
from .text import type_name

_SCOPES = (
    "Singleton",
    "Reusable",
    "ActivityScoped",
    "FragmentScoped",
    "ViewModelScoped",
    "ActivityRetainedScoped",
)
_KNOWN_DI = frozenset(
    {
        "Provides", "Binds", "BindsInstance", "Inject", "Module", "InstallIn", "Named", "Qualifier",
        "Scope", "IntoSet", "IntoMap", "AssistedInject", "Assisted", "AssistedFactory",
        "ApplicationContext", "ActivityContext", "Component", "Subcomponent", *_SCOPES,
    }
)  # fmt: skip
_CAP_WORD = re.compile(r"\b[A-Z]\w*")
_KOIN_DEF = re.compile(
    r"(?<![\w.])(singleOf|factoryOf|scopedOf|viewModelOf|workerOf|single|factory|scoped|"
    r"viewModel|worker)\s*(?:<\s*([\w.]+)\s*>)?\s*[({]"
)
_KOIN_START = re.compile(r"(?<![\w.])startKoin\s*[({]")
_KOIN_MODULES = re.compile(r"(?<![\w.])modules\s*\(")
_KOIN_MODULE_INIT = re.compile(r"=\s*(?:org\.koin\.dsl\.)?module\s*(?:\([^)]*\))?\s*\{")
_CONSTRUCTOR_REF = re.compile(r"\s*\(?\s*::\s*([A-Z]\w*)")
_VM_FUNCS = (
    "hiltViewModel|viewModel|koinViewModel|viewModels|activityViewModels|navGraphViewModels|"
    "sharedViewModel|getViewModel|koinNavViewModel"
)
_VM_GENERIC = re.compile(rf"(?<![\w.])(?:{_VM_FUNCS})\s*<\s*([\w.]+)\s*>")
_VM_DECLARED = re.compile(
    r":\s*([A-Z][\w.]*)\s*\??\s*=\s*(?:hiltViewModel|viewModel|koinViewModel|sharedViewModel)\s*[(<]"
)
_VM_PROVIDER = re.compile(
    r"ViewModelProvider\s*\([^)]*\)\s*(?:\[\s*([\w.]+)\s*::\s*class|\.get\s*\(\s*([\w.]+)\s*::\s*class)"
)
_VM_DEFAULT_CALLS = frozenset(_VM_FUNCS.split("|"))
_STATE_TYPES = re.compile(
    r"\b(?:Mutable)?(?:StateFlow|SharedFlow|LiveData|State)\b|\bFlow\s*<|\bmutableStateOf\b"
)
_KOIN_INJECT = frozenset({"inject", "get", "koinViewModel", "viewModel", "koinInject"})


def _find(annotations: tuple[Annotation, ...], name: str) -> tuple[Annotation | None, str | None]:
    for annotation in annotations:
        if annotation.simple == name and annotation.use_site is None:
            level = annotation.level(accepted(name))
            if level:
                return annotation, level
    return None, None


def _note(level: str, what: str) -> str | None:
    return (
        None
        if level == "confirmed"
        else f"@{what} matches by name only; no import shows its package"
    )


def extract_di(run: Run) -> None:
    _annotated_types(run)
    _injection_points(run)
    _koin(run)
    _viewmodel_uses(run)
    _viewmodel_details(run)
    store = run.store
    if any(
        store.has(make_id("technology", t))
        for t in ("hilt", "dagger", "room", "kapt", "ksp", "data_binding", "navigation_safeargs")
    ):
        store.limit(
            "annotation_processor_output_not_analysed",
            "project",
            "classes generated by annotation processors (Hilt_*, Dagger*, *_Impl, binding classes) "
            "are not in the sources and are not analysed",
            affects_completeness=False,
        )


def _role_fact(
    run: Run,
    kind: str,
    info: FileInfo,
    decl: TypeInfo,
    annotation: Annotation,
    level: str,
    attrs: dict,
    framework: str,
) -> str:
    evidence = [info.view.evidence(annotation.offset)]
    fact_id = run.fact(
        kind,
        decl.fqn,
        basis="source",
        status=level,  # type: ignore[arg-type]
        note=_note(level, annotation.simple),
        evidence=evidence,
        attrs={"class": decl.fqn, "framework": framework, **attrs},
        tags=(*run.path_tags(info.path), f"di:{framework}"),
    )
    run.store.relate(
        fact_id,
        "role_of",
        make_id("type", decl.fqn),
        basis="source",
        status=level,  # type: ignore[arg-type]
        evidence=evidence,
        note=_note(level, annotation.simple),
    )
    return fact_id


def _annotated_types(run: Run) -> None:
    store = run.store
    for info, decl in run.app_types():
        if run.expired():
            return
        annotation, level = _find(decl.annotations, "HiltAndroidApp")
        if annotation and level:
            _role_fact(run, "hilt_application", info, decl, annotation, level, {}, "hilt")
        annotation, level = _find(decl.annotations, "AndroidEntryPoint")
        if annotation and level:
            _role_fact(run, "hilt_android_entry", info, decl, annotation, level, {}, "hilt")
            for role in ("activity", "fragment", "service", "receiver", "view", "custom_view"):
                store.annotate(
                    make_id(role, decl.fqn),
                    attrs={"hilt": True},
                    tags=("di:hilt",),
                    evidence=[info.view.evidence(annotation.offset)],
                )
        annotation, level = _find(decl.annotations, "HiltViewModel")
        if annotation and level:
            _role_fact(run, "hilt_viewmodel", info, decl, annotation, level, {}, "hilt")
            store.annotate(make_id("viewmodel", decl.fqn), attrs={"hilt": True}, tags=("di:hilt",))
        annotation, level = _find(decl.annotations, "HiltWorker")
        if annotation and level:
            _role_fact(run, "hilt_worker", info, decl, annotation, level, {}, "hilt")
        annotation, level = _find(decl.annotations, "EntryPoint")
        if annotation and level:
            _role_fact(
                run, "hilt_entry_point", info, decl, annotation, level, _install_attrs(decl), "hilt"
            )
        annotation, level = _find(decl.annotations, "Module")
        if annotation and level:
            framework = _module_framework(info, annotation)
            if framework == "koin":
                _role_fact(run, "koin_module", info, decl, annotation, level, {}, "koin")
            else:
                _dagger_module(run, info, decl, annotation, level, framework)
        for name in ("Component", "Subcomponent"):
            annotation, level = _find(decl.annotations, name)
            if annotation and level:
                attrs: dict = {"component_kind": name.lower()}
                modules = annotation.arg("modules")
                if modules:
                    attrs["modules"] = modules.class_refs()
                _role_fact(run, "dagger_component", info, decl, annotation, level, attrs, "dagger")
        annotation, level = _find(decl.annotations, "AssistedFactory")
        if annotation and level:
            _role_fact(run, "di_assisted_factory", info, decl, annotation, level, {}, "dagger")
        _injectable(run, info, decl)


def _install_attrs(decl: TypeInfo) -> dict:
    install, _ = _find(decl.annotations, "InstallIn")
    arg = install.arg() if install else None
    return {"installed_in": arg.class_refs()} if arg else {}


def _module_framework(info: FileInfo, annotation: Annotation) -> str:
    if annotation.resolution.fqn == "org.koin.core.annotation.Module":
        return "koin"
    imports = import_index(info.source)
    if annotation.resolution.fqn == "dagger.Module":
        return "hilt" if imports.imports_from("dagger.hilt") else "dagger"
    if imports.imports_from("org.koin"):
        return "koin"
    return "hilt" if imports.imports_from("dagger.hilt") else "dagger"


def _dagger_module(
    run: Run, info: FileInfo, decl: TypeInfo, annotation: Annotation, level: str, framework: str
) -> None:
    store = run.store
    attrs = _install_attrs(decl)
    bindings = [m for m in decl.members if _binding_kind(m)]
    attrs["provides"] = sum(1 for m in bindings if _binding_kind(m) == "provides")
    attrs["binds"] = sum(1 for m in bindings if _binding_kind(m) == "binds")
    module_id = _role_fact(run, "di_module", info, decl, annotation, level, attrs, framework)
    for member in bindings:
        kind = _binding_kind(member)
        scopes = tuple(sorted({a.simple for a in member.annotations if a.simple in _SCOPES}))
        qualifiers = tuple(
            sorted(
                {
                    a.simple
                    for a in member.annotations
                    if a.simple not in _KNOWN_DI and a.use_site is None
                }
            )
        )
        battrs: dict = {
            "binding_kind": kind or "",
            "module": decl.fqn,
            "provided_type": member.type_text,
            "params": tuple(f"{p.name}: {p.type_text}" for p in member.params),
        }
        if scopes:
            battrs["scopes"] = scopes
        if qualifiers:
            battrs["qualifiers"] = qualifiers
        named = next((a for a in member.annotations if a.simple == "Named"), None)
        if named and named.arg() and named.arg().string_value:  # type: ignore[union-attr]
            battrs["named"] = named.arg().string_value  # type: ignore[union-attr]
        evidence = [info.view.evidence(member.offset)]
        binding_id = run.fact(
            "di_binding",
            f"{decl.fqn}#{member.signature}",
            basis="source",
            status=level,  # type: ignore[arg-type]
            note=_note(level, "Provides/Binds"),
            evidence=evidence,
            attrs=battrs,
            tags=(*run.path_tags(info.path), f"di:{framework}"),
        )
        store.relate(
            module_id,
            "declares_binding",
            binding_id,
            basis="source",
            status=level,  # type: ignore[arg-type]
            evidence=evidence,
            note=_note(level, "Provides/Binds"),
        )
        provided = _project_type(run, info, decl, type_name(member.type_text))
        if provided is not None:
            fqn, exact = provided
            store.relate(
                binding_id,
                "provides",
                make_id("type", fqn),
                basis="source",
                status="confirmed" if exact and level == "confirmed" else "inferred",
                evidence=evidence,
                note=None
                if exact and level == "confirmed"
                else "matched by name or by an unconfirmed annotation",
            )
            if kind == "binds" and member.params:
                impl = _project_type(run, info, decl, member.params[0].type_simple)
                if impl is not None:
                    store.relate(
                        make_id("type", fqn),
                        "bound_to",
                        make_id("type", impl[0]),
                        basis="source",
                        status="confirmed"
                        if impl[1] and exact and level == "confirmed"
                        else "inferred",
                        evidence=evidence,
                        note=None
                        if impl[1] and exact and level == "confirmed"
                        else "matched by name or by an unconfirmed annotation",
                    )


def _binding_kind(member: Member) -> str | None:
    if member.kind != "function":
        return None
    for name, kind in (("Provides", "provides"), ("Binds", "binds")):
        annotation, _ = _find(member.annotations, name)
        if annotation:
            return kind
    return None


def _project_type(
    run: Run, info: FileInfo, owner: TypeInfo | None, name: str
) -> tuple[str, bool] | None:
    if not name:
        return None
    resolved = run.resolver.resolve(info.source, name, owner.fqn if owner else None)
    if resolved.fqn and resolved.fqn in run.types:
        return resolved.fqn, resolved.exact
    return None


def _injectable(run: Run, info: FileInfo, decl: TypeInfo) -> None:
    store = run.store
    annotation = level = None
    params = ()
    for candidate in decl.constructor_annotations:
        if candidate.simple in ("Inject", "AssistedInject"):
            annotation, level = _find((candidate,), candidate.simple)
            params = decl.constructor_params
    if annotation is None:
        for member in decl.members:
            if member.kind == "constructor":
                for name in ("Inject", "AssistedInject"):
                    found, found_level = _find(member.annotations, name)
                    if found:
                        annotation, level, params = found, found_level, member.params
    if annotation is None or level is None:
        return
    scopes = tuple(sorted({a.simple for a in decl.annotations if a.simple in _SCOPES}))
    attrs: dict = {
        "dependencies": tuple(f"{p.name}: {p.type_text}" for p in params),
        "assisted": annotation.simple == "AssistedInject",
    }
    if scopes:
        attrs["scopes"] = scopes
    evidence = [info.view.evidence(annotation.offset)]
    fact_id = run.fact(
        "di_injectable",
        decl.fqn,
        basis="source",
        status=level,  # type: ignore[arg-type]
        note=_note(level, annotation.simple),
        evidence=evidence,
        attrs={"class": decl.fqn, **attrs},
        tags=(*run.path_tags(info.path), "di:inject"),
    )
    store.relate(
        fact_id,
        "role_of",
        make_id("type", decl.fqn),
        basis="source",
        status=level,  # type: ignore[arg-type]
        evidence=evidence,
        note=_note(level, annotation.simple),
    )
    for param in params:
        _inject_edges(run, info, decl, make_id("type", decl.fqn), param.type_text, evidence, level)


def _inject_edges(
    run: Run,
    info: FileInfo,
    owner: TypeInfo,
    source_id: str,
    type_text: str,
    evidence: list,
    level: str,
) -> None:
    for word in dict.fromkeys(_CAP_WORD.findall(type_text)):
        found = _project_type(run, info, owner, word)
        if found is None or make_id("type", found[0]) == source_id:
            continue
        exact = found[1] and level == "confirmed"
        run.store.relate(
            source_id,
            "injects",
            make_id("type", found[0]),
            basis="source",
            status="confirmed" if exact else "inferred",
            evidence=evidence,
            note=None if exact else "matched by name or by an unconfirmed annotation",
        )


def _injection_points(run: Run) -> None:
    """``@Inject`` fields and setters: the class receives a dependency without a constructor."""
    for info, decl in run.app_types():
        for member in decl.members:
            if member.kind not in ("property", "field"):
                continue
            annotation, level = _find(member.annotations, "Inject")
            if annotation is None or level is None:
                continue
            _inject_edges(
                run,
                info,
                decl,
                make_id("type", decl.fqn),
                member.type_text,
                [info.view.evidence(member.offset)],
                level,
            )


# -- Koin ------------------------------------------------------------------------------------------


def _koin(run: Run) -> None:
    store = run.store
    modules_by_name: dict[str, str] = {}
    pending_starts: list[tuple[str, FileInfo, tuple[int, int]]] = []
    for info in run.app_sources():
        masked = info.view.masked
        members = [*info.top_level, *(m for d in info.types for m in d.members)]
        for member in members:
            if member.kind != "property" or member.init_name != "module":
                continue
            span = _module_span(info, member)
            if span is None:
                continue
            owner = member.owner
            subject = f"{owner}#{member.name}"
            module_id = run.fact(
                "koin_module",
                subject,
                basis="source",
                evidence=[info.view.evidence(member.offset)],
                attrs={"name": member.name, "owner": owner},
                tags=(*run.path_tags(info.path), "di:koin"),
            )
            modules_by_name.setdefault(member.name, module_id)
            _koin_definitions(run, info, member, module_id, subject, span)
        if "startKoin" in masked:
            for match in _KOIN_START.finditer(masked):
                span = lambda_span(info, match.end() - 1, len(masked))
                start_id = run.fact(
                    "koin_start",
                    f"{info.path}:{info.view.line(match.start())}",
                    basis="source",
                    evidence=[info.view.evidence(match.start())],
                    attrs={"file": info.path},
                    tags=(*run.path_tags(info.path), "di:koin"),
                )
                if span is not None:
                    pending_starts.append((start_id, info, span))
    for start_id, info, span in pending_starts:
        for call in _KOIN_MODULES.finditer(info.view.masked, span[0], span[1]):
            end = info.view.group_end(call.end() - 1)
            if end is None:
                continue
            for name in re.findall(r"[A-Za-z_]\w*", info.view.masked[call.end() : end - 1]):
                if name in modules_by_name:
                    store.relate(
                        start_id,
                        "loads_module",
                        modules_by_name[name],
                        basis="source",
                        evidence=[info.view.evidence(call.start())],
                    )
    for info in run.app_sources():
        if not import_index(info.source).imports_from("org.koin"):
            continue
        for decl in info.types:
            for member in decl.members:
                if member.kind == "property" and member.init_name in _KOIN_INJECT:
                    text = member.init_generic or member.type_text
                    _inject_edges(
                        run,
                        info,
                        decl,
                        make_id("type", decl.fqn),
                        text,
                        [info.view.evidence(member.offset)],
                        "confirmed",
                    )


def _module_span(info: FileInfo, member: Member) -> tuple[int, int] | None:
    match = _KOIN_MODULE_INIT.search(info.view.masked, member.offset, member.offset + 400)
    if match is None:
        return None
    brace = match.end() - 1
    close = info.view.close.get(brace)
    return (brace, close) if close is not None else None


def _koin_definitions(
    run: Run, info: FileInfo, member: Member, module_id: str, subject: str, span: tuple[int, int]
) -> None:
    store = run.store
    masked = info.view.masked
    owner = run.types.get(member.owner)
    for match in _KOIN_DEF.finditer(masked, span[0] + 1, span[1]):
        kind = match.group(1)
        bound: str | None = None
        implementation: str | None = None  # ``single<Repo> { RepoImpl(get()) }`` -> RepoImpl
        if kind.endswith("Of"):
            ref = _CONSTRUCTOR_REF.match(masked, match.end() - 1)
            bound = ref.group(1) if ref else None
        else:
            body = lambda_span(info, match.end() - 1, span[1])
            created = None
            if body:
                created = next(
                    (n for n, _ in project_calls(info, body) if n in run.resolver.by_simple), None
                )
            if match.group(2):
                bound = match.group(2).rsplit(".", 1)[-1]
                implementation = created if created != bound else None
            else:
                bound = created
        if not bound:
            continue
        evidence = [info.view.evidence(match.start())]
        run.fact(
            "koin_definition",
            f"{subject}#{kind} {bound}",
            basis="source",
            evidence=evidence,
            attrs={"definition_kind": kind, "type": bound, "module": subject},
            tags=(*run.path_tags(info.path), "di:koin"),
        )
        found = _project_type(run, info, owner, bound)
        if found is not None:
            store.relate(
                module_id,
                "provides",
                make_id("type", found[0]),
                basis="source",
                status="confirmed" if found[1] else "inferred",
                evidence=evidence,
                note=None if found[1] else "the type is matched by name only",
            )
            impl = _project_type(run, info, owner, implementation) if implementation else None
            if impl is not None:
                exact = found[1] and impl[1]
                store.relate(
                    make_id("type", found[0]),
                    "bound_to",
                    make_id("type", impl[0]),
                    basis="source",
                    status="confirmed" if exact else "inferred",
                    evidence=evidence,
                    note=None if exact else "a type is matched by name only",
                )


# -- ViewModels ------------------------------------------------------------------------------------


def _viewmodel_target(
    run: Run, info: FileInfo, owner: TypeInfo | None, name: str
) -> tuple[str, bool] | None:
    found = _project_type(run, info, owner, name.rsplit(".", 1)[-1])
    if found is None:
        return None
    role = make_id("viewmodel", found[0])
    return (role if run.store.has(role) else make_id("type", found[0]), found[1])


def _source_for(run: Run, info: FileInfo, offset: int) -> tuple[str, TypeInfo | None]:
    function = info.function_at(offset)
    holder = info.type_at(offset)
    if function is not None:
        composable = make_id("composable", f"{function.owner}#{function.signature}")
        if run.store.has(composable):
            return composable, holder
    if holder is not None:
        return make_id("type", holder.fqn), holder
    return make_id("file", info.path), None


def _viewmodel_uses(run: Run) -> None:
    store = run.store
    for info in run.app_sources():
        if run.expired():
            return
        masked = info.view.masked
        found: list[tuple[int, str]] = []
        for pattern in (_VM_GENERIC, _VM_DECLARED):
            found.extend((m.start(), m.group(1)) for m in pattern.finditer(masked))
        for match in _VM_PROVIDER.finditer(masked):
            found.append((match.start(), match.group(1) or match.group(2)))
        for offset, name in found:
            source_id, owner = _source_for(run, info, offset)
            target = _viewmodel_target(run, info, owner, name)
            if target is not None and target[0] != source_id:
                store.relate(
                    source_id,
                    "uses_viewmodel",
                    target[0],
                    basis="source",
                    status="confirmed" if target[1] else "inferred",
                    evidence=[info.view.evidence(offset)],
                    note=None if target[1] else "the ViewModel class is matched by name only",
                )
        members = [*info.top_level, *(m for d in info.types for m in d.members)]
        for member in members:
            if member.kind == "property" and member.init_name in _VM_DEFAULT_CALLS:
                name = member.init_generic or type_name(member.type_text)
                holder = run.types.get(member.owner)
                target = _viewmodel_target(run, info, holder, name) if name else None
                source_id = make_id("type", member.owner)
                if target is not None and store.has(source_id) and target[0] != source_id:
                    store.relate(
                        source_id,
                        "uses_viewmodel",
                        target[0],
                        basis="source",
                        status="confirmed" if target[1] else "inferred",
                        evidence=[info.view.evidence(member.offset)],
                        note=None if target[1] else "the ViewModel class is matched by name only",
                    )


def _viewmodel_details(run: Run) -> None:
    store = run.store
    for fact_id in store.ids_of_kind("viewmodel"):
        decl = run.types.get(fact_id.split(":", 1)[1])
        if decl is None:
            continue
        info = run.infos.get(decl.path)
        if info is None or decl.body is None:
            continue
        holders = [
            f"{m.name}: {m.type_text}"
            for m in decl.members
            if m.kind == "property" and _STATE_TYPES.search(m.type_text or "")
        ]
        masked = info.view.masked[decl.body[0] : decl.body[1]]
        attrs: dict = {}
        if holders:
            attrs["state_holders"] = tuple(holders[:20])
        if "viewModelScope" in masked:
            attrs["uses_viewmodel_scope"] = True
        if any("SavedStateHandle" in p.type_text for p in decl.constructor_params):
            attrs["uses_saved_state_handle"] = True
        if attrs:
            store.annotate(fact_id, attrs=attrs)
