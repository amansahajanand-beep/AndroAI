"""False positives found by running the review engine over AntennaPod (Phase 4a, second project).

AntennaPod is Java-heavy, uses the Groovy Gradle DSL, XML layouts and Play Services. Every defect
below has a twin proving that the genuine error is still reported.
"""

import pytest
from sample_project import MAIN, broken, good_project

from androai_codegen.review import ProjectFiles, ReviewEngine, ReviewReport

APP_GRADLE = "app/build.gradle.kts"
CORE_KTX = "    implementation(libs.androidx.core.ktx)\n"
LAYOUT = "app/src/main/res/layout/screen.xml"
RES_VALUES = "app/src/main/res/values"


def review(files) -> ReviewReport:
    return ReviewEngine().review(ProjectFiles.from_mapping(files))


def found(files) -> list[tuple[str, str, str]]:
    return sorted((f.rule, f.file.rsplit("/", 1)[-1], f.key) for f in review(files).findings)


def with_files(extra: dict[str, str], base=None) -> dict:
    project = dict(base if base is not None else good_project())
    project.update(extra)
    return project


def layout(*attrs: str) -> str:
    body = "\n".join(f'    <TextView android:text="{a}" />' for a in attrs)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f"{body}\n</LinearLayout>\n"
    )


def java(*lines: str) -> str:
    return "package com.example.todo;\n\n" + "\n".join(lines) + "\n"


def with_dependency(coordinate: str) -> dict:
    return broken({APP_GRADLE: (CORE_KTX, f'    implementation("{coordinate}")\n' + CORE_KTX)})


# --- 1. resources generated by Gradle (resValue) ----------------------------------------------


def test_resource_defined_by_resvalue_in_kotlin_dsl_is_defined():
    files = broken(
        {
            APP_GRADLE: (
                "    defaultConfig {\n",
                '    defaultConfig {\n        resValue("string", "brand_name", "Todo")\n',
            )
        }
    )
    files = with_files({LAYOUT: layout("@string/brand_name")}, files)
    assert found(files) == []


def test_resource_defined_by_resvalue_in_a_groovy_shared_script_is_defined():
    # AntennaPod keeps `resValue "string", "app_name", ...` in a common.gradle shared by modules.
    shared = "\n".join(
        [
            "android {",
            "    buildTypes {",
            '        release { resValue "string", "brand_name", "Todo" }',
            '        debug { resValue "string", "brand_name", "Todo Debug" }',
            "    }",
            "}",
        ]
    )
    files = with_files({"common.gradle": shared, LAYOUT: layout("@string/brand_name")})
    assert found(files) == []  # defined twice (release/debug) is not a duplicate resource


def test_resvalue_defines_only_its_own_type_and_name():
    shared = 'android { defaultConfig { resValue "string", "brand_name", "Todo" } }\n'
    files = with_files(
        {
            "common.gradle": shared,
            LAYOUT: layout("@string/other_name", "@color/brand_name"),
        }
    )
    assert found(files) == [
        ("resource.unresolved", "screen.xml", "color/brand_name"),
        ("resource.unresolved", "screen.xml", "string/other_name"),
    ]


# --- 2. resources a dependency provides -------------------------------------------------------

MATERIAL = "com.google.android.material:material:1.12.0"
GMS = "com.google.android.gms:play-services-base:18.0.0"
PREFERENCE = "androidx.preference:preference:1.2.1"
APPCOMPAT = "androidx.appcompat:appcompat:1.7.0"


def test_string_provided_by_the_material_library_is_not_unresolved():
    ref = layout("@string/appbar_scrolling_view_behavior")
    assert found(with_files({LAYOUT: ref}, with_dependency(MATERIAL))) == []
    # Twin: without the dependency nothing provides it.
    assert found(with_files({LAYOUT: ref})) == [
        ("resource.unresolved", "screen.xml", "string/appbar_scrolling_view_behavior")
    ]


def test_integer_provided_by_play_services_is_not_unresolved():
    ref = layout("@integer/google_play_services_version")
    assert found(with_files({LAYOUT: ref}, with_dependency(GMS))) == []
    assert found(with_files({LAYOUT: ref})) == [
        ("resource.unresolved", "screen.xml", "integer/google_play_services_version")
    ]


def test_ids_provided_by_preference_and_appcompat_are_not_unresolved():
    code = {
        f"{MAIN}/Ids.java": java(
            "import com.example.todo.R;",
            "",
            "class Ids { int a = R.id.recycler_view; int b = R.id.select_dialog_listview; }",
        )
    }
    base = with_dependency(PREFERENCE)
    base[APP_GRADLE] = base[APP_GRADLE].replace(
        CORE_KTX, f'    implementation("{APPCOMPAT}")\n' + CORE_KTX
    )
    assert found(with_files(code, base)) == []
    assert found(with_files(code)) == [
        ("resource.unresolved", "Ids.java", "id/recycler_view"),
        ("resource.unresolved", "Ids.java", "id/select_dialog_listview"),
    ]


def test_a_typo_next_to_a_library_resource_is_still_unresolved():
    ref = layout("@string/appbar_scrolling_view_behaviour")  # British spelling: not a real name
    assert found(with_files({LAYOUT: ref}, with_dependency(MATERIAL))) == [
        ("resource.unresolved", "screen.xml", "string/appbar_scrolling_view_behaviour")
    ]


# --- 3. <attr> inside <declare-styleable> may only reference an attribute ---------------------

STYLEABLES = """<?xml version="1.0" encoding="utf-8"?>
<resources>
    <declare-styleable name="CircularProgressBar">
        <attr name="foregroundColor" format="color" />
    </declare-styleable>
    <declare-styleable name="PlaybackSpeedIndicatorView">
        <attr name="foregroundColor" /> <!-- format omitted to avoid double definition -->
    </declare-styleable>
</resources>
"""


def test_styleable_attr_without_a_format_is_a_reference_not_a_second_definition():
    assert found(with_files({f"{RES_VALUES}/styleable.xml": STYLEABLES})) == []


def test_two_attr_definitions_with_a_format_are_still_duplicates():
    both = STYLEABLES.replace(
        '<attr name="foregroundColor" />', '<attr name="foregroundColor" format="color" />'
    )
    names = [
        (rule, key) for rule, _, key in found(with_files({f"{RES_VALUES}/styleable.xml": both}))
    ]
    assert names == [("resource.duplicate", "attr/foregroundColor")] * 2


def test_the_same_top_level_attr_twice_is_still_a_duplicate():
    twice = (
        '<resources>\n    <attr name="tint" format="color" />\n'
        '    <attr name="tint" format="color" />\n</resources>\n'
    )
    assert len(found(with_files({f"{RES_VALUES}/attrs.xml": twice}))) == 2


# --- 4. well-formed XML that uses a DOCTYPE (tool configuration, not Android) -----------------

CHECKSTYLE = (
    '<?xml version="1.0"?>\n<!DOCTYPE module PUBLIC\n  "-//Checkstyle//DTD Checkstyle '
    'Configuration 1.3//EN"\n  "https://checkstyle.org/dtds/configuration_1_3.dtd">\n'
    '<module name="Checker"/>\n'
)


def test_doctype_in_a_tool_config_outside_resources_is_not_a_syntax_error():
    report = review(with_files({"config/checkstyle/checkstyle.xml": CHECKSTYLE}))
    assert report.findings == []
    assert report.files_unparsed == ["config/checkstyle/checkstyle.xml"]  # honest: not parsed


def test_doctype_inside_resources_or_the_manifest_is_still_reported():
    for path in (f"{RES_VALUES}/x.xml", "lib/src/main/AndroidManifest.xml"):
        assert [f.rule for f in review(with_files({path: CHECKSTYLE})).findings] == [
            "xml.malformed"
        ], path


# --- 5. enum constants are declarations, not type uses ----------------------------------------


def test_java_enum_constant_named_like_a_library_type_is_not_a_use_of_it():
    files = with_files(
        {
            f"{MAIN}/ReorderItem.java": java(
                "public final class ReorderItem {",
                "    public enum ViewType {",
                "        Section,",
                "        Header",
                "    }",
                "}",
            )
        }
    )
    assert found(files) == []


def test_kotlin_enum_entries_with_arguments_and_bodies_are_declarations():
    files = with_files(
        {
            f"{MAIN}/Kind.kt": "package com.example.todo\n\n"
            "enum class Kind(val code: Int) {\n"
            "    Header(1),\n"
            '    Response(2) { override fun toString() = "r" },\n'
            "    Footer(3);\n\n    fun label() = name\n}\n"
        }
    )
    assert found(files) == []


def test_a_real_use_of_a_library_type_name_next_to_an_enum_is_still_missing():
    files = with_files(
        {
            f"{MAIN}/ReorderItem.java": java(
                "public final class ReorderItem {",
                "    public enum ViewType { Section, Footer }",
                "    private Header header;",
                "}",
            )
        }
    )
    assert found(files) == [("import.missing", "ReorderItem.java", "Header")]


# --- 6. known limitation: nested types inherited from a library superclass --------------------


@pytest.mark.xfail(
    strict=True,
    reason="A nested type inherited from a library superclass (NanoHTTPD.Response) needs no "
    "import, but library classes are invisible to us. Excusing names inside classes that extend "
    "library types would also hide a missing `Context` import in every Fragment.",
)
def test_nested_type_inherited_from_a_library_superclass_needs_no_import():
    files = with_files(
        {
            f"{MAIN}/Bin.java": java(
                "import fi.iki.elonen.NanoHTTPD;",
                "",
                "public class Bin extends NanoHTTPD {",
                "    public Response serve(IHTTPSession session) { return null; }",
                "}",
            )
        }
    )
    assert found(files) == []


def test_missing_import_inside_a_class_extending_a_library_type_is_still_reported():
    files = with_files(
        {
            f"{MAIN}/Frag.java": java(
                "import androidx.fragment.app.Fragment;",
                "",
                "public class Frag extends Fragment {",
                "    private Context context;",
                "}",
            )
        }
    )
    assert found(files) == [("import.missing", "Frag.java", "Context")]
